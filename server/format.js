// 텍스트 후처리 유틸 — AI 티가 나는 마크다운 기호 제거 + 어그로(클릭 유도) 제목 지침.
// 생성된 원고에는 종종 **굵게**·## 소제목 같은 마크다운 기호가 그대로 남는데,
// 이 기호들은 발행 화면에 문자 그대로 노출되어 "AI가 쓴 티"를 낸다. 저장 전에 걷어낸다.

/**
 * 본문/제목에서 마크다운 강조·헤딩 기호를 제거해 사람이 쓴 평문으로 만든다.
 * - "## 소제목" → "소제목"   (줄 앞 #, 1~6개)
 * - "**굵게**" / "__굵게__" → "굵게"
 * 보존: 이미지 마커 [이미지: …], 인용 마커 "> "(네이버 인용구 변환용), 불릿("- ", "* ").
 */
function stripAiMarkup(text) {
  return String(text || '')
    .replace(/^\s{0,3}#{1,6}\s*/gm, '')      // 줄 앞 헤딩 기호 제거
    .replace(/\*\*([^*\n]+?)\*\*/g, '$1')     // **굵게** → 굵게
    .replace(/__([^_\n]+?)__/g, '$1')         // __굵게__ → 굵게
    .replace(/\*\*/g, '')                      // 남은 고아 ** 제거
    .replace(/[ \t]+$/gm, '');                 // 기호 제거로 생긴 줄끝 공백 정리
}

// 모든 콘텐츠 제목에 적용하는 "어그로(클릭 유도)" 지침.
// 핵심: 정보를 다 드러내지 않고 결과·반전을 감춰 호기심 격차를 만든다.
// 단, 사실 왜곡·정책 금칙어는 피한다(광고 게재 제한/저품질 판정 방지).
