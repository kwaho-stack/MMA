  '- 제목만 봐도 눌러보고 싶게 과장한다. 결과·핵심을 다 드러내지 말고 살짝 감춰 "궁금해서 못 참게" 만든다(호기심 격차).',
  '- 기법을 적극 활용: 구체적 숫자·기간("3일 만에", "10년"), 질문형("…했더니 벌어진 일?"), 의외성("이것만 했는데"), 손실 회피("모르면 후회").',
  '- 예시 변환: "15분으로 바꾸는 내 몸" → "이것만 했는데 몸이 10년 젊어졌다?"',
